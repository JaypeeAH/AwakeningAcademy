// Writes supabase/seeds/sample_courses.sql: the four sample courses (configs/sampleCourses) as plain SQL,
// for adding them to a database straight from the Supabase SQL editor (e.g. as shared test data).
// The SQL is generated from the same definitions as the in-app "Add a sample course" button, through the
// same Quest Builder conversion, so the two never drift apart. Re-run after editing a sample.
//
//   npm run db:sample-seed

import { createHash } from 'node:crypto'
import { writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createJiti } from 'jiti'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outFile = join(root, 'supabase', 'seeds', 'sample_courses.sql')
const jiti = createJiti(import.meta.url, { alias: { '@': join(root, 'src') } })

const { SAMPLE_COURSES } = await jiti.import('@/configs/sampleCourses')
const { sampleActivityToSaveInput } = await jiti.import('@/utils/sampleCourses')
const { activityKindXpSource } = await jiti.import('@/@types/activities/ActivityKindOptions')

/** Stable ids, so running the seed twice finds the courses it already added instead of duplicating them */
function stableUuid(name) {
    const hex = createHash('sha1').update(`awakening-academy/sample/${name}`).digest('hex')
    const variant = ((parseInt(hex[16], 16) & 0x3) | 0x8).toString(16)
    return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(13, 16)}-${variant}${hex.slice(17, 20)}-${hex.slice(20, 32)}`
}

/** Fixed join codes, so test students can join without looking them up (teachers can reset them) */
const JOIN_CODES = {
    pythagoras: 'SMPMATH1',
    'cells-photosynthesis': 'SMPBIO1',
    'solar-system': 'SMPSPACE1',
    'ancient-egypt': 'SMPEGYPT1',
}

const samples = SAMPLE_COURSES.map((sample) => {
    const id = (name) => stableUuid(`${sample.id}/${name}`)
    const moduleId = id('module')
    return {
        id: id('course'),
        sample: sample.id,
        subjectSlug: sample.subjectSlug,
        title: sample.title,
        description: sample.description,
        joinCode: JOIN_CODES[sample.id],
        module: { id: moduleId, title: sample.module.title, description: sample.module.description },
        activities: sample.activities.map((activity) => {
            let n = 0
            const input = sampleActivityToSaveInput(activity, {
                xpReward: 0, // the database's default for the kind is used instead (see the SQL)
                moduleId,
                prerequisiteIds: (activity.requires ?? []).map((key) => id(`activity/${key}`)),
                newId: () => id(`activity/${activity.key}/${n++}`),
            })
            return {
                id: id(`activity/${activity.key}`),
                kind: activity.kind,
                xpSource: activityKindXpSource[activity.kind],
                title: input.title,
                summary: input.summary,
                body: input.body,
                objectives: input.objectives,
                difficulty: input.difficulty,
                estimatedMinutes: input.estimatedMinutes,
                maxAttempts: input.maxAttempts,
                passingScore: input.passingScore,
                feedbackMode: input.feedbackMode,
                allowSkills: input.allowSkills,
                boss: input.boss,
                prerequisiteIds: input.prerequisiteIds,
                questions: input.questions,
            }
        }),
    }
})

for (const sample of samples) if (!sample.joinCode) throw new Error(`No join code for sample "${sample.sample}"`)
const json = JSON.stringify(samples, null, 2)
if (json.includes('$samples$')) throw new Error('Sample content contains the SQL quote tag $samples$')

const summary = samples
    .map((s) => `--   ${s.joinCode.padEnd(10)} ${s.title} (${s.activities.length} activities)`)
    .join('\n')

const sql = `-- ═══════════════════════════════════════════════════════════════════════════════════════════════════
-- Sample courses (GENERATED by \`npm run db:sample-seed\` from src/configs/sampleCourses — don't edit by hand)
--
-- Adds four ready-made, published courses with lessons (images + YouTube videos), quizzes and a boss
-- battle — the same content as Courses → "Add a sample course". Not a migration: run it yourself in the
-- Supabase SQL editor, after every file in supabase/migrations, whenever you want the samples.
--
--   • Owner: the teacher or administrator whose email you put in v_owner_email below, or (left empty)
--     the oldest administrator account. They become the courses' teacher.
--   • Students join with these codes (the teacher can reset them on the course page):
${summary}
--   • Safe to run again: courses already added are skipped. To remove them, delete the courses
--     (everything inside goes with them).
-- ═══════════════════════════════════════════════════════════════════════════════════════════════════

do $seed$
declare
    v_owner_email text := '';   -- ← optional: e.g. 'teacher@yourschool.org'
    v_owner uuid;
    v_samples jsonb := $samples$${json}$samples$::jsonb;
    v_sample jsonb;
    v_activity jsonb;
    v_course uuid;
    v_subject uuid;
    v_code text;
    v_position integer;
begin
    if v_owner_email <> '' then
        select id into v_owner from public.profiles
        where lower(email) = lower(v_owner_email) and role in ('teacher', 'admin');
        if v_owner is null then
            raise exception 'No teacher or administrator account has the email %', v_owner_email;
        end if;
    else
        select id into v_owner from public.profiles where role = 'admin' order by created_at limit 1;
        if v_owner is null then
            raise exception 'There is no administrator account yet: set v_owner_email to a teacher''s email.';
        end if;
    end if;

    for v_sample in select * from jsonb_array_elements(v_samples) loop
        v_course := (v_sample ->> 'id')::uuid;
        if exists (select 1 from public.courses where id = v_course) then
            raise notice 'Skipped "%": it''s already here.', v_sample ->> 'title';
            continue;
        end if;

        select id into v_subject from public.subjects where slug = v_sample ->> 'subjectSlug';
        if v_subject is null then
            raise exception 'The subject "%" is missing, so "%" can''t be added.', v_sample ->> 'subjectSlug', v_sample ->> 'title';
        end if;

        v_code := v_sample ->> 'joinCode';
        if exists (select 1 from public.courses where join_code = v_code) then
            v_code := upper(left(replace(gen_random_uuid()::text, '-', ''), 8));
        end if;

        insert into public.courses (id, subject_id, title, description, join_code, status, created_by)
        values (v_course, v_subject, v_sample ->> 'title', v_sample ->> 'description', v_code, 'published', v_owner);
        insert into public.course_teachers (course_id, teacher_id) values (v_course, v_owner);
        insert into public.modules (id, course_id, title, description, position)
        values ((v_sample -> 'module' ->> 'id')::uuid, v_course, v_sample -> 'module' ->> 'title',
                v_sample -> 'module' ->> 'description', 0);

        v_position := 0;
        for v_activity in select * from jsonb_array_elements(v_sample -> 'activities') loop
            insert into public.activities (
                id, course_id, module_id, kind, title, summary, body, objectives, difficulty, xp_reward,
                estimated_minutes, max_attempts, passing_score, feedback_mode, allow_skills, allow_bunny_skips,
                xp_repeatable, boss, status, position, published_at, created_by
            ) values (
                (v_activity ->> 'id')::uuid,
                v_course,
                (v_sample -> 'module' ->> 'id')::uuid,
                (v_activity ->> 'kind')::public.activity_kind,
                v_activity ->> 'title',
                v_activity ->> 'summary',
                v_activity ->> 'body',
                array(select jsonb_array_elements_text(v_activity -> 'objectives')),
                (v_activity ->> 'difficulty')::smallint,
                -- The administrator's default XP for this kind of activity
                coalesce((select default_xp from public.xp_rules
                          where source = (v_activity ->> 'xpSource')::public.xp_source), 0),
                (v_activity ->> 'estimatedMinutes')::integer,
                (v_activity ->> 'maxAttempts')::integer,
                (v_activity ->> 'passingScore')::smallint,
                (v_activity ->> 'feedbackMode')::public.feedback_mode,
                (v_activity ->> 'allowSkills')::boolean,
                false,
                false,
                nullif(v_activity -> 'boss', 'null'::jsonb),
                'published',
                v_position,
                now(),
                v_owner
            );
            -- Questions, options, answer keys and prerequisites, through the same function the Quest Builder uses
            perform public.save_activity_content(
                (v_activity ->> 'id')::uuid,
                v_activity -> 'questions',
                array(select jsonb_array_elements_text(v_activity -> 'prerequisiteIds'))::uuid[]
            );
            v_position := v_position + 1;
        end loop;

        insert into public.audit_events (actor_id, action, entity_type, entity_id, details)
        values (v_owner, 'course.sample_added', 'course', v_course::text,
                jsonb_build_object('sample', v_sample ->> 'sample', 'title', v_sample ->> 'title', 'via', 'sql'));
        raise notice 'Added "%" (join code %).', v_sample ->> 'title', v_code;
    end loop;
end
$seed$;
`

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, sql)
console.log(`Wrote ${outFile.slice(root.length + 1)} (${samples.length} courses).`)

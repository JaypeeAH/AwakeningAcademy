// Writes one SQL file per full course in src/configs/courses (e.g. supabase/seeds/finite_mathematics_2.sql),
// for installing it from the Supabase SQL editor for the teacher named in its definition. Uses the same
// Quest Builder conversion as sample courses (utils/sampleCourses), so what the seed stores is exactly
// what the Quest Builder would save. Re-run after editing a course.
//
//   npm run db:course-seed

import { createHash } from 'node:crypto'
import { writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createJiti } from 'jiti'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const jiti = createJiti(import.meta.url, { alias: { '@': join(root, 'src') } })

const { SEEDED_COURSES } = await jiti.import('@/configs/courses')
const { sampleActivityToSaveInput } = await jiti.import('@/utils/sampleCourses')
const { activityKindXpSource } = await jiti.import('@/@types/activities/ActivityKindOptions')

/** Stable ids, so running the seed twice finds the course it already added instead of duplicating it */
function stableUuid(name) {
    const hex = createHash('sha1').update(`awakening-academy/course/${name}`).digest('hex')
    const variant = ((parseInt(hex[16], 16) & 0x3) | 0x8).toString(16)
    return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(13, 16)}-${variant}${hex.slice(17, 20)}-${hex.slice(20, 32)}`
}

function buildCourse(course) {
    const id = (name) => stableUuid(`${course.id}/${name}`)
    return {
        id: id('course'),
        subjectSlug: course.subjectSlug,
        title: course.title,
        description: course.description,
        joinCode: course.joinCode,
        modules: course.modules.map((module, index) => {
            const moduleId = id(`module/${index}`)
            return {
                id: moduleId,
                title: module.title,
                description: module.description,
                activities: module.activities.map((activity) => {
                    let n = 0
                    const input = sampleActivityToSaveInput(activity, {
                        xpReward: 0, // the database's default for the kind is used instead (see the SQL)
                        moduleId,
                        prerequisiteIds: (activity.requires ?? []).map((key) => id(`activity/${key}`)),
                        newId: () => id(`activity/${activity.key}/${n++}`),
                    })
                    return {
                        id: id(`activity/${activity.key}`),
                        kind: activity.kind,
                        xpSource: activityKindXpSource[activity.kind],
                        title: input.title,
                        summary: input.summary,
                        body: input.body,
                        objectives: input.objectives,
                        difficulty: input.difficulty,
                        estimatedMinutes: input.estimatedMinutes,
                        maxAttempts: input.maxAttempts,
                        passingScore: input.passingScore,
                        feedbackMode: input.feedbackMode,
                        allowSkills: input.allowSkills,
                        boss: input.boss,
                        prerequisiteIds: input.prerequisiteIds,
                        questions: input.questions,
                    }
                }),
            }
        }),
    }
}

const sqlString = (value) => `'${value.replace(/'/g, "''")}'`

function courseSql(definition) {
    const course = buildCourse(definition)
    const json = JSON.stringify(course, null, 2)
    if (json.includes('$course$')) throw new Error(`"${definition.title}" contains the SQL quote tag $course$`)
    const activityCount = course.modules.reduce((n, m) => n + m.activities.length, 0)
    const questionCount = course.modules.reduce(
        (n, m) => n + m.activities.reduce((q, a) => q + a.questions.length, 0),
        0,
    )
    const units = course.modules.map((m) => `--     ${m.title} (${m.activities.length} activities)`).join('\n')

    return `-- ═══════════════════════════════════════════════════════════════════════════════════════════════════
-- ${definition.title} (GENERATED by \`npm run db:course-seed\` from src/configs/courses — don't edit by hand)
--
-- Adds the course, published, with ${activityCount} activities and ${questionCount} questions:
${units}
-- Not a migration: run it yourself in the Supabase SQL editor, after every file in supabase/migrations.
--
--   • Teacher: ${definition.ownerEmail}. That account must exist first (sign up, then an administrator
--     makes it a teacher in Admin → Users). They become the course's teacher and its activities' author.
--   • Students join with the code ${course.joinCode} (the teacher can reset it on the course page).
--   • Safe to run again: if the course is already here, nothing changes. To remove it, delete the course
--     (everything inside goes with it).
-- ═══════════════════════════════════════════════════════════════════════════════════════════════════

do $seed$
declare
    v_owner_email text := ${sqlString(definition.ownerEmail)};
    v_owner uuid;
    v_course_data jsonb := $course$${json}$course$::jsonb;
    v_module jsonb;
    v_activity jsonb;
    v_course uuid;
    v_subject uuid;
    v_code text;
    v_module_position integer := 0;
    v_position integer;
begin
    select id into v_owner from public.profiles
    where lower(email) = lower(v_owner_email) and role in ('teacher', 'admin');
    if v_owner is null then
        raise exception 'No teacher account has the email %. Sign up with it, make it a teacher in Admin → Users, then run this again.', v_owner_email;
    end if;

    v_course := (v_course_data ->> 'id')::uuid;
    if exists (select 1 from public.courses where id = v_course) then
        raise notice 'Skipped "%": it''s already here.', v_course_data ->> 'title';
        return;
    end if;

    select id into v_subject from public.subjects where slug = v_course_data ->> 'subjectSlug';
    if v_subject is null then
        raise exception 'The subject "%" is missing.', v_course_data ->> 'subjectSlug';
    end if;

    v_code := v_course_data ->> 'joinCode';
    if exists (select 1 from public.courses where join_code = v_code) then
        v_code := upper(left(replace(gen_random_uuid()::text, '-', ''), 8));
    end if;

    insert into public.courses (id, subject_id, title, description, join_code, status, created_by)
    values (v_course, v_subject, v_course_data ->> 'title', v_course_data ->> 'description', v_code, 'published', v_owner);
    insert into public.course_teachers (course_id, teacher_id) values (v_course, v_owner);

    for v_module in select * from jsonb_array_elements(v_course_data -> 'modules') loop
        insert into public.modules (id, course_id, title, description, position)
        values ((v_module ->> 'id')::uuid, v_course, v_module ->> 'title', v_module ->> 'description', v_module_position);
        v_module_position := v_module_position + 1;
    end loop;

    -- Activities after every module, so prerequisites may point into an earlier unit
    v_position := 0;
    for v_module in select * from jsonb_array_elements(v_course_data -> 'modules') loop
        for v_activity in select * from jsonb_array_elements(v_module -> 'activities') loop
            insert into public.activities (
                id, course_id, module_id, kind, title, summary, body, objectives, difficulty, xp_reward,
                estimated_minutes, max_attempts, passing_score, feedback_mode, allow_skills, allow_bunny_skips,
                xp_repeatable, boss, status, position, published_at, created_by
            ) values (
                (v_activity ->> 'id')::uuid,
                v_course,
                (v_module ->> 'id')::uuid,
                (v_activity ->> 'kind')::public.activity_kind,
                v_activity ->> 'title',
                v_activity ->> 'summary',
                v_activity ->> 'body',
                array(select jsonb_array_elements_text(v_activity -> 'objectives')),
                (v_activity ->> 'difficulty')::smallint,
                -- The administrator's default XP for this kind of activity
                coalesce((select default_xp from public.xp_rules
                          where source = (v_activity ->> 'xpSource')::public.xp_source), 0),
                (v_activity ->> 'estimatedMinutes')::integer,
                (v_activity ->> 'maxAttempts')::integer,
                (v_activity ->> 'passingScore')::smallint,
                (v_activity ->> 'feedbackMode')::public.feedback_mode,
                (v_activity ->> 'allowSkills')::boolean,
                false,
                false,
                nullif(v_activity -> 'boss', 'null'::jsonb),
                'published',
                v_position,
                now(),
                v_owner
            );
            v_position := v_position + 1;
        end loop;
    end loop;

    -- Questions, options, answer keys and prerequisites, through the same function the Quest Builder uses
    for v_module in select * from jsonb_array_elements(v_course_data -> 'modules') loop
        for v_activity in select * from jsonb_array_elements(v_module -> 'activities') loop
            perform public.save_activity_content(
                (v_activity ->> 'id')::uuid,
                v_activity -> 'questions',
                array(select jsonb_array_elements_text(v_activity -> 'prerequisiteIds'))::uuid[]
            );
        end loop;
    end loop;

    insert into public.audit_events (actor_id, action, entity_type, entity_id, details)
    values (v_owner, 'course.created', 'course', v_course::text,
            jsonb_build_object('title', v_course_data ->> 'title', 'via', 'sql seed'));
    raise notice 'Added "%" for % (join code %).', v_course_data ->> 'title', v_owner_email, v_code;
end
$seed$;
`
}

const seedsDir = join(root, 'supabase', 'seeds')
mkdirSync(seedsDir, { recursive: true })
for (const definition of SEEDED_COURSES) {
    const outFile = join(seedsDir, `${definition.id.replace(/-/g, '_')}.sql`)
    writeFileSync(outFile, courseSql(definition))
    console.log(`Wrote ${outFile.slice(root.length + 1)}.`)
}

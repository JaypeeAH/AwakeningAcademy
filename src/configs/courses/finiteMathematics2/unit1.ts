    '> [!NOTE]\n> **Example 2: fruit salad.** Choose 3 of 7 kinds of fruit.\n>\n> C(7, 3) = (7 × 6 × 5) ÷ (3 × 2 × 1) = 210 ÷ 6 = **35 salads**.',
